"""Labeling-pool builder + weak auto-labels for the acceptance queries.

Hand-labeling all ~1,150 images x 5 queries is wasteful; instead, for each
query the human labels a POOL that is the union of:

- the top-15 results from three deliberately different systems — ablation
  variants (a) vanilla-clip-whole, (c) fashionclip-regions and
  (d) regions+attr-filter — so the pool is not biased toward any one system,
- every image whose stored ImageAttributes satisfy the conjunctive predicates
  from ``predicates_from_parsed(RuleParser().parse(query))`` (the structural
  attribute path can surface relevant images that no embedding ranks highly).

Outputs (written next to this module):

- eval/label_pool.json   {query_id: [image_id, ...]} — what a human labels.
- eval/labels.auto.yaml  {labels: {query_id: [...]}} — the attribute-satisfying
  images as WEAK auto-labels. They inherit every VLM extraction error and miss
  everything the extractor missed: a human MUST confirm/extend them against the
  pool before saving the result as eval/labels.yaml (which is what
  eval.harness.load_labels reads).

CLI:
    python -m eval.label_pool --config config/default.yaml
"""
from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
from typing import Mapping, Sequence

import yaml

from core.config import load_config, resolve
from eval.ablations import AblationRunner, load_store
from eval.harness import load_queries
from indexer.storage.base import VectorStore
from retriever.parsing.rule_parser import RuleParser
from retriever.search.engine import predicates_from_parsed

log = logging.getLogger(__name__)

POOL_VARIANTS: tuple[str, ...] = (
    "vanilla-clip-whole",
    "fashionclip-regions",
    "regions+attr-filter",
)
POOL_TOP_N = 15

_OUT_DIR = Path(__file__).resolve().parent


def attribute_matches(
    store: VectorStore,
    query_text: str,
    parser: RuleParser | None = None,
) -> set[str]:
    """Images whose stored attributes satisfy the query's conjunctive predicates.

    Returns the empty set when parsing yields no required predicates (e.g. the
    style-only query q4) — an empty conjunction would vacuously match the whole
    corpus, which is useless as a label signal.
    """
    parser = parser or RuleParser()
    parsed = parser.parse(query_text)
    required, excluded = predicates_from_parsed(parsed)
    if not required:
        return set()
    return set(store.find_images(required, excluded))


def build_label_pool(
    runner: AblationRunner,
    queries: Sequence[Mapping[str, str]],
    *,
    top_n: int = POOL_TOP_N,
    variants: Sequence[str] = POOL_VARIANTS,
) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """Return (pool, auto_labels), each {query_id: sorted [image_id, ...]}.

    A variant that cannot be built (missing dep / unbuilt module) only thins
    the pool — it never aborts pool construction.
    """
    parser = RuleParser()
    auto: dict[str, list[str]] = {
        str(q["id"]): sorted(attribute_matches(runner.store, str(q["text"]), parser))
        for q in queries
    }

    fns = {}
    for name in variants:
        try:
            fns[name] = runner.variant(name)
        except Exception:  # noqa: BLE001 — pool degrades gracefully
            log.exception("pool variant %s unavailable — pool will be thinner", name)

    pool: dict[str, list[str]] = {}
    for q in queries:
        qid, text = str(q["id"]), str(q["text"])
        ids: set[str] = set(auto[qid])
        for name, fn in fns.items():
            try:
                ids.update(fn(text, top_n))
            except Exception:  # noqa: BLE001
                log.exception("pool variant %s failed on query %s", name, qid)
        pool[qid] = sorted(ids)
        log.info("query %s: pool=%d candidates (%d weak auto-labels)",
                 qid, len(pool[qid]), len(auto[qid]))
    return pool, auto


def write_outputs(
    pool: Mapping[str, list[str]],
    auto: Mapping[str, list[str]],
    out_dir: str | Path | None = None,
) -> tuple[Path, Path]:
    """Write label_pool.json and labels.auto.yaml. Returns their paths."""
    od = Path(out_dir) if out_dir is not None else _OUT_DIR
    od.mkdir(parents=True, exist_ok=True)

    pool_path = od / "label_pool.json"
    with open(pool_path, "w", encoding="utf-8") as f:
        json.dump(dict(pool), f, indent=2, ensure_ascii=False)

    auto_path = od / "labels.auto.yaml"
    header = (
        "# WEAK AUTO-LABELS — NOT ground truth. Generated by eval/label_pool.py\n"
        "# from VLM-extracted attribute predicates; they inherit every extraction\n"
        "# error and miss whatever the extractor missed. A human must confirm and\n"
        "# extend them against eval/label_pool.json, then save the confirmed set\n"
        "# as eval/labels.yaml (the file eval.harness.load_labels reads).\n"
    )
    with open(auto_path, "w", encoding="utf-8") as f:
        f.write(header)
        yaml.safe_dump({"labels": {k: list(v) for k, v in auto.items()}},
                       f, default_flow_style=False, sort_keys=True, allow_unicode=True)
    log.info("wrote %s and %s", pool_path, auto_path)
    return pool_path, auto_path


def main(argv: Sequence[str] | None = None) -> None:
    """CLI: build the labeling pool + weak auto-labels for the acceptance queries."""
    parser = argparse.ArgumentParser(
        prog="python -m eval.label_pool",
        description="Build eval/label_pool.json and eval/labels.auto.yaml.")
    parser.add_argument("--config", default=None)
    parser.add_argument("--store-dir", default=None,
                        help="persisted index dir (default: <artifacts_dir>/index)")
    parser.add_argument("--images-dir", default=None)
    parser.add_argument("--queries", default=None)
    parser.add_argument("--top-n", type=int, default=POOL_TOP_N)
    parser.add_argument("--out-dir", default=None,
                        help="output directory (default: the eval/ package dir)")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s")

    cfg = load_config(args.config)
    queries = load_queries(args.queries or resolve(cfg, "eval.queries_file"))
    store = load_store(cfg, args.store_dir)
    images_dir = Path(args.images_dir) if args.images_dir else resolve(cfg, "paths.images_dir")
    runner = AblationRunner(cfg, store, images_dir)

    pool, auto = build_label_pool(runner, queries, top_n=args.top_n)
    write_outputs(pool, auto, out_dir=args.out_dir)


if __name__ == "__main__":
    main()
